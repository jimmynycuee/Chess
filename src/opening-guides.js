// 依開局全名找說明與相符的變例。
export function findGuide(opening) {
  if (!opening?.family) return null;
  let g = OPENING_GUIDES[opening.family];
  if (g?.alias) g = OPENING_GUIDES[g.alias];
  if (!g) return null;
  const variation = g.variations?.find((v) => opening.name.includes(v.match)) || null;
  return { ...g, variation };
}
